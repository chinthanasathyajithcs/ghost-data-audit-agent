"""Write code/evaluation/usage_report.md from the usage summary of the last agent run.

    python3 code/main.py                                   # the run that produces output.csv
    python3 code/evaluation/write_usage_report.py          # summarises code/usage/last_run_usage.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(EVAL_DIR.parent))

from deletion_audit.config import LAST_RUN_USAGE_FILE  # noqa: E402

REPORT = EVAL_DIR / "usage_report.md"
TASK_NAMES = {"intent": "Request intent (Stage 2)", "extraction": "Screenshot/PDF extraction (Stage 4A)",
              "category": "Data category (Stage 6)"}


def input_total(t: dict) -> int:
    return t["input_tokens"] + t["cache_creation_input_tokens"] + t["cache_read_input_tokens"]


def row(name: str, t: dict, requests: int) -> str:
    total = input_total(t) + t["output_tokens"]
    return (f"| {name} | {t['calls']} | {t['input_tokens']:,} | {t['cache_creation_input_tokens']:,} | "
            f"{t['cache_read_input_tokens']:,} | {input_total(t):,} | {t['output_tokens']:,} | {total:,} | "
            f"{total / requests:,.1f} | ${t['cost_usd']:.4f} | ${t['cost_usd'] / requests:.6f} | {t['duration_s']:.0f} |")


def overall(groups: dict) -> dict:
    keys = ("calls", "input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens",
            "cost_usd", "duration_s")
    return {k: sum(g[k] for g in groups.values()) for k in keys}


def build(usage: dict) -> str:
    requests = usage["requests"]
    header = ("| | Calls | Input (uncached) | Cache write | Cache read | Input total | Output | Total tokens | "
              "Tokens / request | Cost | Cost / request | Wall time (s) |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
    models, tasks = usage["models"], usage.get("tasks", {})
    total = overall(models)
    lines = [
        "# Usage report — final full-dataset run",
        "",
        f"This report summarises the run that produced `output.csv`: all **{requests}** requests in "
        f"`dataset/deletion_requests.csv`, finished at {usage['time']}, started with **empty LLM caches** so every "
        "model call happened during the run (cached answers counted in this run: "
        f"{usage.get('cache_hits', 0)}). Generated by `code/evaluation/write_usage_report.py` from "
        "`code/usage/last_run_usage.json`.",
        "",
        "## Provider and models",
        "",
        "| Provider | Access | Model | Used for |",
        "|---|---|---|---|",
    ]
    for model in sorted(models):
        lines.append(f"| Anthropic | Claude Code CLI (`claude -p`, headless, JSON schema) | `{model}` | "
                     + ", ".join(TASK_NAMES[t] for t in sorted(tasks)) + " |")
    lines += ["", "Token and cost figures are the per-call usage the Claude Code CLI reports (`modelUsage`, "
              "list-price `costUSD`). The run used the CLI with the user's Claude plan, so the cost is an "
              "**estimate at list price**, not an amount billed. No other model or provider was used; the "
              "rest of the pipeline is deterministic Python.", "", "## Per model", "", header]
    lines += [row(f"`{m}`", t, requests) for m, t in sorted(models.items())]
    lines += [row("**Overall**", total, requests), "", "## Per task", "", header]
    lines += [row(TASK_NAMES.get(name, name), t, requests) for name, t in sorted(tasks.items())]
    lines += [row("**Overall**", overall(tasks) if tasks else total, requests), "",
              "## Notes", "",
              f"- Averages are over all {requests} requests. Calls are batched (25 request texts or record "
              "signatures per call; one call per screenshot or PDF), so most requests share calls.",
              "- Data-category calls are answered three times per batch and decided by majority vote (Stage 6, "
              "§7.3.1), so 45 category calls cover 15 batches of record signatures.",
              "- *Input total* = uncached input + cache-write input + cache-read input (prompt caching by the "
              "CLI).",
              "- After this run the answers are cached in `code/deletion_audit/cache/` and shipped: a rerun "
              "makes **0** calls and costs nothing, and reproduces `output.csv` exactly.", ""]
    return "\n".join(lines)


def main() -> int:
    usage = json.loads(LAST_RUN_USAGE_FILE.read_text(encoding="utf-8"))
    REPORT.write_text(build(usage), encoding="utf-8")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
